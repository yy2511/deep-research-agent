/** Explicit opt-in offline component QA. Serve the QA build locally before running. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.env.DRA_QA_URL;
if (!base || !['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw new Error('DRA_QA_URL must be an explicitly supplied localhost fixture URL');
const directory = process.env.DRA_QA_SCREENSHOTS ?? '/tmp/user-management-screenshots';
await fs.mkdir(directory, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.DRA_BROWSER_EXECUTABLE || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = []; page.on('pageerror', error => errors.push(String(error)));
await page.route('**/*', route => ['localhost','127.0.0.1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
const click = text => page.getByRole('button', { name: text, exact: true }).click();
const pause = () => page.waitForTimeout(550);
try {
 await page.goto(base); await pause();
 assert.equal(await page.locator('tbody tr').count(), 4);
 await page.screenshot({ path: `${directory}/users-desktop.png`, fullPage: true });
 await page.locator('tr').filter({ hasText: '合成普通用户' }).getByRole('button').click(); await pause();
 assert.equal(await page.locator('dialog[open]').count(), 1);
 await page.getByLabel('每日研究次数').fill('7'); await click('保存个人额度'); await click('取消修改');
 assert.equal(await page.locator('#writes').innerText(), '0');
 await click('保存个人额度'); await page.getByRole('button', { name: '确认保存', exact: true }).evaluate(b => { b.click(); b.click(); }); await pause();
 assert.equal(await page.locator('#writes').innerText(), '1');
 assert.equal(await page.getByLabel('每日研究次数').inputValue(), '7');
 await page.screenshot({ path: `${directory}/user-detail-desktop.png`, fullPage: true });
 await click('关闭'); assert.equal(await page.locator('dialog[open]').count(), 0);
 await click('切换为管理员'); await pause();
 await page.locator('tr').filter({ hasText: '合成负责人' }).getByRole('button').click(); await pause();
 assert.equal(await page.getByRole('button', { name: '停用账号', exact: true }).count(), 0); await click('关闭');
 await page.locator('tr').filter({ hasText: '合成普通用户' }).getByRole('button').click(); await pause();
 assert.equal(await page.getByRole('option', { name: '不限次数', exact: true }).count(), 0); await click('关闭');
 await click('下次请求模拟409'); await click('刷新'); await pause();
 assert.match(await page.locator('main').innerText(), /模拟版本冲突/);
 await click('刷新'); await pause();
 await click('下次请求模拟403'); await click('刷新'); await pause();
 assert.equal(await page.locator('tbody tr').count(), 0);
 assert.equal(await page.getByRole('button', { name: '刷新', exact: true }).isDisabled(), true);
 await page.reload(); await pause();
 await page.getByLabel('查找账号').fill('synthetic-4'); await click('查询'); await pause(); assert.equal(await page.locator('tbody tr').count(), 1);
 await page.locator('tbody tr').getByRole('button').click(); await pause();
 assert.match(await page.locator('dialog').innerText(), /不支持个人覆盖/); await click('查看平台试用配置'); assert.equal(await page.locator('dialog[open]').count(), 0);
 await page.reload(); await pause();
 await page.getByRole('button', { name: '负责人管理', exact: true }).click(); await pause();
 await page.getByLabel('新负责人账号 ID').fill('2'); await click('核对账号'); await pause();
 await page.getByLabel('当前账号密码').fill('synthetic-only'); await click('验证密码'); await pause();
 assert.equal(await page.getByRole('button', { name: '确认移交并退出登录', exact: true }).isDisabled(), true);
 await page.screenshot({ path: `${directory}/owner-confirm-desktop.png`, fullPage: true });
 await click('取消移交'); assert.equal(await page.getByRole('button', { name: '确认移交并退出登录', exact: true }).count(), 0);
 await page.reload(); await pause(); await page.setViewportSize({ width: 390, height: 844 }); await pause();
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
 await page.screenshot({ path: `${directory}/users-mobile.png`, fullPage: true });
 await page.locator('tr').filter({ hasText: '合成普通用户' }).getByRole('button').click(); await pause();
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
 await page.screenshot({ path: `${directory}/user-detail-mobile.png`, fullPage: true });
 await page.keyboard.press('Escape'); assert.equal(await page.locator('dialog[open]').count(), 0);
 assert.deepEqual(errors, []);
 console.log('PASS: synthetic component desktop/mobile, filters, role restrictions, cancel/close/Escape, quota save and duplicate click, 409/403 cleanup, owner verification and cancel; no JS errors.');
} finally { await browser.close(); }
